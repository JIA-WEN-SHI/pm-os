export function defaultStageDraft(stage: number): StageDraft {
  return {
    inputs: ['', '', ''],
    sourceIds: [],
    criteria: stageContracts[stage].criteria.map(
      ([label, target, method], i) => ({
        id: `s${stage + 1}-m${i + 1}`,
        label,
        target,
        method
      })
    )
  }
}

// Content follows the approved execution spec and stage contracts; presentation is shared.
export function stageContentPrompt(stage: number) {
  const c = stageContracts[stage]
  return `\n本阶段内容契约：${c.output}\n分析顺序：${c.process.join(' → ')}。\n必须依据本阶段内容契约组织章节与表格；页面共用交互，不代表共用分析内容。继承上游结论、依据和未解决问题，并解释本阶段如何继续处理。对缺口只追问资料无法回答且影响结论的内容，一轮最多 3 个。材料不足时保留缺口、原因和影响，不凭空填满表格；不适用项写明理由。缺证据时不能用一份未来计划代替本阶段应给出的分析结论。区分事实、用户陈述、模拟、假设与建议，呈现矛盾，不把案例的具体结论迁移为新项目事实。用户明确修改的范围与接受的限制需保留；既有人工配置和已确认记录不能被默认模板静默替换。确认、实测和发布记录只引用实际发生的记录，没有则标待确认、未执行或待发布。`
}
